import json
from pathlib import Path
from pydoc import tempfile_pager
import tempfile
from typing import Any

from _pyrepl.pager import os
from documenthub.core.exceptions import MetadataError


class MetadataStore:
    def __init__(self, root:Path):
        ## expands it into actual home-directory path depends on os and user account,i.e ~/myproject
        # it will be represent and converts into absolute path
        # we need this because, later we compare document paths against the project root
        self.root = root.expanduser().resolve()
        ## path look like i.e projects/documenthub-demo/.documenthub/metadata
        self.metadata_root = self.root / ".documenthub" / "metadata"
    def path_for(self, document_path:Path)->Path:
        """where document metadata should be stored"""
        ## input will be path of file, and output returns metadata store path
        source = document_path.expanduser().resolve()
        try:
            ## check this path is subpath of root path
            relative = source.relative_to(self.root)
        except ValueError as exc:
            raise MetadataError(f"Document must be inside meatadata root: {source}") from exc
        return self.metadata_root / relative.parent / f"{relative.name}.json"



    def read(self, document_path:Path)->dict[str, Any]:
        """Read metadata from its JSON file"""
        metadata_path = self.path_for(document_path)
        ## check this path is exist or not
        if not metadata_path.exists():
            return {} ## we can't fail, if user put different document path, that not generated by DocumentHub
        try:
            value = json.loads(metadata_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise MetadataError(f"Could not read metadata file: {metadata_path}") from exc
        if not isinstance(value, dict):
            raise MetadataError(f"Metadata must contain a JSON Object: {metadata_path}")
        return value


    def write(self, document_path:Path, metadata: dict[str, Any]):
        """save metadata into a JSON file"""
        metadata_path = self.path_for(document_path)
        metadata_path.parent.mkdir(parents=True, exist_ok=True)
        descriptor, temp_name = tempfile.mkstemp(
            prefix=".metadata-",
            suffix=".tmp",
            dir=metadata_path.parent
        )
        temp_path = Path(temp_name)
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8")as stream:
                json.dump(metadata, stream, ensure_ascii=False, indent=2)
            os.replace(temp_path, metadata_path)
            return metadata_path
        except Exception as exc:
            temp_path.unlink(missing_ok=True)
            raise MetadataError(f"Could not write metadata file: {metadata_path}") from exc
